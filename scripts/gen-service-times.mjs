#!/usr/bin/env node
// Regenerates src/data/service-times.snapshot.ts from Studio's published location records.
// Usage: node scripts/gen-service-times.mjs <https://studio/api/content/locations | records.json>
// Needs Node >= 22.18 (runs the TypeScript core directly). Refuses input that does not validate.
import { readFileSync, writeFileSync } from "node:fs";
import { resolveTimes } from "../src/lib/service-times-core.ts";

const src = process.argv[2];
if (!src) { console.error("usage: gen-service-times.mjs <url|file>"); process.exit(2); }
const raw = /^https?:/.test(src) ? await (await fetch(src)).json() : JSON.parse(readFileSync(src, "utf8"));
const records = Array.isArray(raw) ? raw : raw.locations;
const empty = { campuses: [{ slug: "hays", name: "Hays", services: [] }, { slug: "colby", name: "Colby", services: [] }] };
const data = resolveTimes(records, empty);
for (const c of data.campuses) if (c.services.length === 0) { console.error(`no valid record for ${c.slug}; snapshot not written`); process.exit(1); }
const out = `// GENERATED by scripts/gen-service-times.mjs from Studio's published location records. Do not edit by hand.
// The only file outside Studio's data that may hold clock times (tests/service-times.test.ts).
import type { ServiceTimesData } from "@/lib/service-times-core";

export const SERVICE_TIMES_SNAPSHOT: ServiceTimesData = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(new URL("../src/data/service-times.snapshot.ts", import.meta.url), out);
console.log("wrote src/data/service-times.snapshot.ts");
